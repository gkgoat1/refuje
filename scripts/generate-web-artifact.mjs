#!/usr/bin/env node
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

try {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const artifactPath = resolve(root, "out/Refuje.sol/Refuje.json");
  const outputPath = resolve(root, "web/src/refujeArtifact.ts");
  const artifact = JSON.parse(await readFile(artifactPath, "utf8"));
  const bytecode = artifact?.bytecode?.object;

  if (typeof bytecode !== "string" || !bytecode.startsWith("0x") || bytecode.length < 4) {
    throw new Error(`No Refuje creation bytecode found in ${artifactPath}. Run forge build first.`);
  }

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(
    outputPath,
    `// Generated by scripts/generate-web-artifact.mjs; do not edit.\nexport const REFUJE_BYTECODE = ${JSON.stringify(bytecode)} as const;\n`,
  );
  console.log(`Wrote ${outputPath}`);
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
